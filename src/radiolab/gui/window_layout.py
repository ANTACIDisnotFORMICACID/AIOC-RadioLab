"""主窗口控件布局与信号连接。"""
from PySide6.QtCore import Qt
from PySide6.QtWidgets import (QAbstractItemView, QCheckBox, QComboBox, QDoubleSpinBox,
                               QHBoxLayout, QHeaderView, QLabel, QLineEdit, QProgressBar,
                               QPushButton, QSpinBox, QTableWidget, QVBoxLayout, QWidget)


class WindowLayout:
    def build_layout(self, config_path) -> None:
        self.setWindowTitle("RadioLab · 桌面终端（V0.3 预览）")
        self.resize(1120, 760)

        root = QWidget()
        layout = QVBoxLayout(root)
        devices = QHBoxLayout()
        self.tx_choice = QComboBox()
        self.tx_choice.addItem("选择 TX 输出", None)
        self.rx_choice = QComboBox()
        self.rx_choice.addItem("选择 RX 输入", None)
        self.ptt_choice = QComboBox()
        self.ptt_choice.addItem("PTT 串口未检查", None)
        self.refresh_devices_button = QPushButton("刷新设备")
        for label, choice in (("TX 输出", self.tx_choice), ("RX 输入", self.rx_choice),
                              ("PTT 串口", self.ptt_choice)):
            devices.addWidget(QLabel(label))
            devices.addWidget(choice, 1)
        devices.addWidget(self.refresh_devices_button)
        layout.addLayout(devices)
        self.device_status = QLabel("设备尚未检查；刷新仅枚举，不打开串口或声卡")
        layout.addWidget(self.device_status)

        recording = QHBoxLayout()
        self.record_seconds = QDoubleSpinBox()
        self.record_seconds.setRange(0.1, 120.0)
        self.record_seconds.setValue(45.0)
        self.record_seconds.setSuffix(" s")
        self.record_output = QLineEdit()
        self.record_output.setPlaceholderText("留空则自动保存到数据库旁的 recordings 目录")
        self.record_button = QPushButton("开始录音")
        self.stop_record_button = QPushButton("停止录音")
        self.stop_record_button.setEnabled(False)
        recording.addWidget(QLabel("最长"))
        recording.addWidget(self.record_seconds)
        recording.addWidget(self.record_output, 1)
        recording.addWidget(self.record_button)
        recording.addWidget(self.stop_record_button)
        layout.addLayout(recording)
        self.record_status = QLabel("录音未开始；须明确选择 RX 输入")
        layout.addWidget(self.record_status)

        listening = QHBoxLayout()
        self.listen_button = QPushButton("自动监听文本")
        self.stop_listen_button = QPushButton("停止监听")
        self.stop_listen_button.setEnabled(False)
        listening.addWidget(QLabel("文本监听：使用所选 RX 输入和最长时长，录音自动保存"))
        listening.addWidget(self.listen_button)
        listening.addWidget(self.stop_listen_button)
        layout.addLayout(listening)
        self.listen_status = QLabel("自动监听未开始；仅接收音频，不操作 PTT")
        layout.addWidget(self.listen_status)
        level_row = QHBoxLayout()
        self.rx_level_bar = QProgressBar()
        self.rx_level_bar.setRange(0, 80)
        self.rx_level_bar.setValue(0)
        self.rx_level_bar.setTextVisible(False)
        self.rx_level_text = QLabel("RX 输入电平：未监听；音量不能证明收到有效帧")
        level_row.addWidget(self.rx_level_bar, 1)
        level_row.addWidget(self.rx_level_text, 2)
        layout.addLayout(level_row)

        replay = QHBoxLayout()
        self.local_choice = QComboBox()
        self.local_choice.addItem("选择本地输出", None)
        self.replay_gain = QDoubleSpinBox()
        self.replay_gain.setRange(0.01, 0.20)
        self.replay_gain.setSingleStep(0.01)
        self.replay_gain.setDecimals(2)
        self.replay_gain.setValue(0.05)
        self.replay_check = QCheckBox("已确认此输出未接电台或 VOX")
        self.replay_button = QPushButton("回放选中 WAV")
        self.stop_replay_button = QPushButton("停止回放")
        self.stop_replay_button.setEnabled(False)
        replay.addWidget(QLabel("本地回放"))
        replay.addWidget(self.local_choice, 1)
        replay.addWidget(QLabel("增益"))
        replay.addWidget(self.replay_gain)
        replay.addWidget(self.replay_check)
        replay.addWidget(self.replay_button)
        replay.addWidget(self.stop_replay_button)
        layout.addLayout(replay)
        self.replay_status = QLabel("回放默认锁定；须选择本地输出并确认其未连接电台")
        layout.addWidget(self.replay_status)

        encoding = QHBoxLayout()
        self.tx_message = QLineEdit()
        self.tx_message.setPlaceholderText("最多 32 字节 UTF-8 文本")
        self.tx_sequence = QSpinBox()
        self.tx_sequence.setRange(0, 255)
        self.tx_output = QLineEdit()
        self.tx_output.setPlaceholderText("留空则自动保存到数据库旁的 encoded 目录")
        self.encode_button = QPushButton("生成文本 WAV")
        encoding.addWidget(QLabel("文本"))
        encoding.addWidget(self.tx_message, 2)
        encoding.addWidget(QLabel("序号"))
        encoding.addWidget(self.tx_sequence)
        encoding.addWidget(self.tx_output, 2)
        encoding.addWidget(self.encode_button)
        layout.addLayout(encoding)
        self.tx_status = QLabel("离线生成 AFSK WAV；此按钮不会发射")
        layout.addWidget(self.tx_status)

        images = QHBoxLayout()
        self.sstv_image = QLineEdit()
        self.sstv_image.setPlaceholderText("输入图片路径")
        self.gallery_button = QPushButton("图片库")
        self.sstv_output = QLineEdit()
        self.sstv_output.setPlaceholderText("留空则自动保存到数据库旁的 encoded 目录")
        self.sstv_encode_button = QPushButton("生成图像 WAV")
        images.addWidget(QLabel("图片"))
        images.addWidget(self.sstv_image, 2)
        images.addWidget(self.gallery_button)
        images.addWidget(self.sstv_output, 2)
        images.addWidget(self.sstv_encode_button)
        layout.addLayout(images)
        self.sstv_status = QLabel("离线生成 Robot36 WAV；此按钮不会发射")
        layout.addWidget(self.sstv_status)

        air = QHBoxLayout()
        self.config_input = QLineEdit(str(config_path) if config_path is not None else "")
        self.config_input.setPlaceholderText("真实发射专用：已完成无辐射台架的 config.toml")
        self.config_edit_button = QPushButton("编辑配置")
        self.air_check = QCheckBox("本次发射已确认授权、频率、接线和 PTT 台架")
        self.air_text_button = QPushButton("发射文本")
        self.air_sstv_button = QPushButton("发射图片")
        self.abort_tx_button = QPushButton("停止发射")
        self.air_text_button.setEnabled(False)
        self.air_sstv_button.setEnabled(False)
        self.abort_tx_button.setEnabled(False)
        air.addWidget(QLabel("配置"))
        air.addWidget(self.config_input, 1)
        air.addWidget(self.config_edit_button)
        air.addWidget(self.air_check)
        air.addWidget(self.air_text_button)
        air.addWidget(self.air_sstv_button)
        air.addWidget(self.abort_tx_button)
        layout.addLayout(air)
        self.air_status = QLabel("真实发射默认锁定；仅用户显式确认后才会操作 PTT")
        layout.addWidget(self.air_status)

        controls = QHBoxLayout()
        self.mode = QComboBox()
        for label, value in (("全部模式", None), ("文本", "text"), ("SSTV", "sstv"), ("音频", "audio")):
            self.mode.addItem(label, value)
        self.search = QLineEdit()
        self.search.setPlaceholderText("搜索文本内容")
        refresh = QPushButton("查询")
        migrate = QPushButton("从 JSONL 导入")
        self.export_button = QPushButton("导出历史 ZIP")
        self.recent_button = QPushButton("最近文件")
        self.decode_button = QPushButton("解码选中 WAV")
        self.text_decode_button = QPushButton("解码文本 WAV")
        copy_cell = QPushButton("复制选中单元格")
        controls.addWidget(self.mode)
        controls.addWidget(self.search, 1)
        controls.addWidget(refresh)
        controls.addWidget(migrate)
        controls.addWidget(self.export_button)
        controls.addWidget(self.recent_button)
        controls.addWidget(self.decode_button)
        controls.addWidget(self.text_decode_button)
        controls.addWidget(copy_cell)
        layout.addLayout(controls)

        self.table = QTableWidget(0, 9)
        self.table.setHorizontalHeaderLabels(("本地时间", "模式", "操作", "结果", "文本", "WAV", "图片", "解码器", "日志"))
        self.table.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)
        self.table.setSelectionBehavior(QAbstractItemView.SelectionBehavior.SelectItems)
        self.table.setAlternatingRowColors(True)
        self.table.setWordWrap(False)
        self.table.setTextElideMode(Qt.TextElideMode.ElideMiddle)
        header = self.table.horizontalHeader()
        for column, width in ((0, 165), (1, 65), (2, 75), (3, 60), (5, 160), (6, 160), (7, 125), (8, 130)):
            header.resizeSection(column, width)
        header.setSectionResizeMode(4, QHeaderView.ResizeMode.Stretch)
        layout.addWidget(self.table, 1)
        self.preview = QLabel("选择含图片的记录查看预览")
        self.preview.setAlignment(Qt.AlignmentFlag.AlignCenter)
        self.preview.setFixedHeight(245)
        self.preview.setStyleSheet("border: 1px solid #bbb")
        self.preview.hide()
        layout.addWidget(self.preview)
        self.status = QLabel()
        layout.addWidget(self.status)
        self.setCentralWidget(root)

        refresh.clicked.connect(self.refresh_history)
        self.search.returnPressed.connect(self.refresh_history)
        self.mode.currentIndexChanged.connect(self.refresh_history)
        migrate.clicked.connect(self.migrate_history)
        self.export_button.clicked.connect(self.start_history_export)
        self.recent_button.clicked.connect(self.open_recent_files)
        copy_cell.clicked.connect(self.copy_selected_cell)
        self.decode_button.clicked.connect(self.start_decode_selected)
        self.text_decode_button.clicked.connect(self.start_text_decode_selected)
        self.table.currentCellChanged.connect(self.show_selected_image)
        self.refresh_devices_button.clicked.connect(self.refresh_devices)
        self.record_button.clicked.connect(self.start_record)
        self.stop_record_button.clicked.connect(self.stop_record)
        self.listen_button.clicked.connect(self.start_text_listen)
        self.stop_listen_button.clicked.connect(self.stop_text_listen)
        self.replay_button.clicked.connect(self.start_replay_selected)
        self.stop_replay_button.clicked.connect(self.stop_replay)
        self.encode_button.clicked.connect(self.start_text_encode)
        self.sstv_encode_button.clicked.connect(self.start_sstv_encode)
        self.gallery_button.clicked.connect(self.open_image_gallery)
        self.air_check.toggled.connect(self.air_toggle_changed)
        self.config_edit_button.clicked.connect(self.open_config_editor)
        self.air_text_button.clicked.connect(self.start_on_air_text)
        self.air_sstv_button.clicked.connect(self.start_on_air_sstv)
        self.abort_tx_button.clicked.connect(self.abort_on_air)
        self.refresh_history()

